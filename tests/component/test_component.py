# Invalid Time Parameter Component Test

@pytest.mark.parametrize(
        "endtime, timestep, writeInterval",
        [
        # Test 1: endtime must be positive
        ("0","0.01","0.01"),

        # Test 2: endtime must not be negative
        ("-5","0.01","0.01"),

        # Test 3: timestep must be positive
        ("5","0","0.01"),

        # Test 4: timestep must not be negative
        ("5","-0.01","0.01"),

        # Test 5: writeInterval must be positive
        ("5","0.01","0"),

        # Test 6: writeInterval must not be negative
        ("5","0.01","-2"),

        # Test 7: writeInterval must be greater than or equal to timestep
        ("5","0.02","0.01"),
            ]
        )

def test_invalid_time_parameters(endtime, timestep, writeInterval):
    result = subprocess.run(
            [
                str(BINARY),
                "implicit",
                "40",
                "40",
                endtime,
                timestep,
                writeInterval,
                "1","3"
            ],
            capture_output=True,
            text=True,
            cwd=PROJECT_ROOT,
            timeout=30
        )
    assert result.returncode!=0
    assert(
            "Invalid time parameters" in result.stderr
            or "Invalid write interval" in result.stderr
            or "endtime, dt and writeInterval must be positive!" in result.stderr
            or "writeInterval must be atleast greater than the timestep." in result.stderr
        )
