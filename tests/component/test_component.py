import subprocess
from pathlib import Path
import pytest


# Locate the project directory
PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent

# Locate the C++ executable
BINARY = PROJECT_ROOT / "build" / "brusselator"

def test_solver_execution(): # test that executes the C++ binary
    # the following launches C++ executable from python
    result = subprocess.run(
            [
                str(BINARY),
                "rk4", #solver
                "50", # nx
                "50", # ny
                "5",  # endtime
                "0.01",# timestep 
                "1",   # writeInterval
                "1",   # Ca
                "3",   # Cb
        ],
        capture_output=True, # captures the output generated by C++ program
        text=True, # tells python to capture the output as strings rather than bytes
        cwd=PROJECT_ROOT,
        timeout=30)
    
    #check whether the solver executed succesfully
    assert result.returncode == 0

    print("Solver executed successfully!")


